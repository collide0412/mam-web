export function getFoodById(id: string): FoodItem | undefined {
  return foodCatalog.find((food) => food.id === id)
}

export function searchFoods(query: string, favorites: string[] = [], recent: string[] = []): SearchResult[] {
  const normalized = normalizeText(query)
  const tokens = normalized.split(' ').filter(Boolean)
  return foodCatalog.flatMap(food => {
    const names = [food.name, ...food.aliases].map(normalizeText)
    if (tokens.length && !names.some(name => tokens.every(token => name.includes(token)))) return []
    const exact = names.includes(normalized) && normalized !== ''
    const position = recent.indexOf(food.id)
    return [{ ...food, score: (exact ? 1000 : 0) + (favorites.includes(food.id) ? 50 : 0) + (position < 0 ? 0 : 100 - position) }]
  }).sort((a, b) => b.score - a.score)
}

export function getRecommendationCandidates(_profile: Profile, recentMeals: MealEntry[] = []): FoodItem[] {
  const recentIds = [...new Set([...recentMeals].sort((a, b) => b.timestamp.localeCompare(a.timestamp)).slice(0, 5).map(meal => meal.foodId))]
  return [...foodCatalog].sort((a, b) => Number(recentIds.includes(a.id)) - Number(recentIds.includes(b.id))).slice(0, 4)
}
